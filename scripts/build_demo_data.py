"""Write frontend/src/demo/data.js from the synthetic mailbox, using the REAL rule filter.

  python scripts/build_demo_data.py

The browser demo then shows what InBoxIQ's actual rules decide, not invented results.
"""
import json
import os
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("GEMINI_API_KEY", "")
os.environ.setdefault("GMAIL_TOKEN_FILE", "none.json")

from src.brain import quick_rule_filter  # noqa: E402

rows = [json.loads(x) for x in (ROOT / "eval/data/synthetic_mailbox.jsonl").read_text().splitlines() if x]
now = datetime(2026, 11, 26, 9, 0)
emails, review, hidden = [], [], []
for i, r in enumerate(rows[:80]):
    is_hidden = quick_rule_filter(r["sender"], r["subject"], r["body"], [], "") is not None
    status = "ARCHIVE" if is_hidden else ("TASK" if r["label"] == "needs_action" else "FYI_KNOWLEDGE")
    if r["hard"] and not is_hidden:
        status = "REVIEW"
        review.append(r["id"])
    if any(w in r["subject"].lower() for w in ("approval", "review", "confirm")) and status == "TASK":
        status = "REPLY"
    if is_hidden:
        hidden.append(r["id"])
    emails.append({
        "id": r["id"], "thread_id": r["id"], "sender": r["sender"], "subject": r["subject"],
        "summary": r["body"][:140], "content": r["body"], "status": status, "is_done": False,
        "priority": "high" if r["label"] == "needs_action" else "low",
        "received_at": (now - timedelta(minutes=37 * i)).isoformat(),
        "deadlines": [], "actions_required": [],
    })

out = ROOT / "frontend/src/demo/data.js"
out.write_text(
    "// Generated by scripts/build_demo_data.py from eval/data/synthetic_mailbox.jsonl. Do not edit.\n"
    f"export const EMAILS = {json.dumps(emails, indent=1)};\n"
    f"export const REVIEW_IDS = {json.dumps(review)};\n"
    f"export const HIDDEN_IDS = {json.dumps(hidden)};\n",
    encoding="utf-8",
)
print(f"wrote {len(emails)} emails ({len(hidden)} hidden by rules, {len(review)} to review) to {out}")
